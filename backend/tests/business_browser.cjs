const assert=require("node:assert/strict");
const fs=require("node:fs");
const {chromium}=require("playwright");
(async()=>{
 const fixture=JSON.parse(fs.readFileSync(process.env.RIGHTS360_E2E_FIXTURE,"utf8"));
 const browser=await chromium.launch({headless:true});
 try{
  const context=await browser.newContext({acceptDownloads:true});
  const page=await context.newPage();
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto("http://127.0.0.1:8500/portal");
  const visible=async selector=>page.locator(selector).waitFor({state:"visible",timeout:15000});
  const submit=async(selector,path,method,status)=>{
    const [response]=await Promise.all([page.waitForResponse(r=>new URL(r.url()).pathname===path&&r.request().method()===method),page.locator(selector+" button[type=submit]").click()]);
    assert.equal(response.status(),status,path);
    return response.json();
  };
  await page.locator("#org").fill(fixture.org);
  await page.locator("#email").fill(fixture.email);
  await page.locator("#password").fill(fixture.password);
  await page.locator("#login-form button[type=submit]").click();
  await visible("#session-view");
  await page.locator("#open-institution").click();
  await visible("#institution-view");
  await page.getByRole("button",{name:"Ouvrir le registre",exact:true}).click();
  await visible("#artist-form");
  await page.locator("#artist-number").fill("E2E-ARTIST");
  await page.locator("#artist-name").fill("Synthetic Artist");
  await page.locator("#artist-status").selectOption("active");
  const artist=await submit("#artist-form","/api/v1/artists","POST",201);
  await page.locator("#artist-list").getByText(/Synthetic Artist/).first().waitFor();
  await page.getByRole("button",{name:"Ouvrir les œuvres",exact:true}).click();
  await visible("#work-form");
  await page.locator("#work-reference").fill("E2E-WORK");
  await page.locator("#work-title").fill("Synthetic Work");
  await page.locator("#work-artist").fill(artist.id);
  const work=await submit("#work-form","/api/v1/works","POST",201);
  await page.locator("#work-list").getByText(/Synthetic Work/).first().waitFor();
  await page.getByRole("button",{name:"Gestion documentaire",exact:true}).click();
  await visible("#documents-form");
  await page.locator("#documents-title").fill("Synthetic contract");
  await page.locator("#documents-subject").selectOption("work_id");
  await page.locator("#documents-subject-id").fill(work.id);
  const doc=await submit("#documents-form","/api/v1/documents","POST",201);
  await visible("#documents-upload");
  const bytes=Buffer.from("%PDF-1.4\nSynthetic test envelope\n%%EOF");
  await page.locator("#documents-file").setInputFiles({name:"test.pdf",mimeType:"application/pdf",buffer:bytes});
  const version=await submit("#documents-upload","/api/v1/documents/"+doc.id+"/versions","POST",201);
  assert.equal(version.version,1);
  const downloadButton=page.getByRole("button",{name:/Télécharger v1/});
  await downloadButton.waitFor();
  const [download]=await Promise.all([page.waitForEvent("download"),downloadButton.click()]);
  assert.deepEqual(fs.readFileSync(await download.path()),bytes);
  await page.locator("#institution-view [data-logout]").click();
  await visible("#login-view");
  assert.deepEqual(errors,[]);
  console.log("Authenticated browser journey PASS: login, artist, work, document, upload, download, logout");
  await context.close();
 }finally{await browser.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
